# Shows
# ─────────────────────────────────────────────────────────────────────────
def get_or_create_show(
    db: Session, movie: models.Movie, screen: models.Screen,
    show_date: date, start_time: str,
) -> Optional[models.Show]:
    existing = (
        db.query(models.Show)
        .filter(
            models.Show.screen_id == screen.id, models.Show.movie_id == movie.id,
            models.Show.date == show_date, models.Show.start_time == start_time,
        )
        .first()
    )
    if existing:
        return None

    # Never overlap another show already scheduled on this screen/date/time.
    clash = (
        db.query(models.Show)
        .filter(models.Show.screen_id == screen.id, models.Show.date == show_date, models.Show.start_time == start_time)
        .first()
    )
    if clash:
        return None

    start_h, start_m = (int(x) for x in start_time.split(":"))
    runtime = movie.duration or 150
    end_dt = datetime(2000, 1, 1, start_h, start_m) + timedelta(minutes=runtime + 25)
    end_time = end_dt.strftime("%H:%M")

    show = models.Show(
        movie_id=movie.id, screen_id=screen.id, date=show_date,
        start_time=start_time, end_time=end_time, price_multiplier=1.0,
    )
    db.add(show)
    db.flush()
    return show


def seed_shows(db: Session, movies: List[models.Movie], theatre_screens: Dict[str, List[models.Screen]]) -> int:
    """Curated, non-combinatorial show distribution:
    - Never for unreleased movies (release_date must be <= today).
    - Classics get a small number of retrospective screenings (1-2 theatres).
    - Current/recent movies get broader distribution across language-affine
      cities, several dates, but not every theatre in every city.
    """
    print("Seeding shows (skipping any movie not yet released)...")
    today = date.today()

    # theatre_name -> city, for filtering by language affinity
    theatre_city = {spec["name"]: spec["city"] for spec in THEATRES}

    created = 0
    for movie in movies:
        if movie.release_date is None or movie.release_date > today:
            continue  # never schedule shows for unreleased movies

        is_classic = movie.release_date < date(2020, 1, 1)
        target_cities = LANGUAGE_CITY_AFFINITY.get(movie.language, [])
        if not target_cities:
            continue

        # Candidate theatres in the movie's affine cities.
        candidate_theatres = [name for name, city in theatre_city.items() if city in target_cities]
        if not candidate_theatres:
            continue

        if is_classic:
            chosen_theatres = candidate_theatres[:2]
            dates_offsets = [3]  # a single retrospective date, ~3 days out
            slots = [SHOW_TIME_SLOTS[1]]  # one afternoon slot
        else:
            chosen_theatres = candidate_theatres[:5]
            dates_offsets = [1, 4, 8]
            slots = SHOW_TIME_SLOTS[:3]

        for theatre_name in chosen_theatres:
            screens = theatre_screens.get(theatre_name, [])
            if not screens:
                continue
            for i, offset in enumerate(dates_offsets):
                show_date = today + timedelta(days=offset)
                screen = screens[i % len(screens)]
                slot = slots[i % len(slots)]
                show = get_or_create_show(db, movie, screen, show_date, slot)
                if show:
                    created += 1
    db.commit()
    print(f"  ✓ {created} new shows created.")
    return created


# ─────────────────────────────────────────────────────────────────────────
def seed_catalog():
    print("Creating tables (no-op if already present)...")
    Base.metadata.create_all(bind=engine)

    db = SessionLocal()
    try:
        handle_synthetic_placeholder(db)
        db.commit()

        theatre_screens = seed_theatres(db)
        movies = seed_movies(db)
        seed_shows(db, movies, theatre_screens)

        print("Demo catalog seeding complete!")
    except Exception as e:
        print(f"Error seeding demo catalog: {e}")
        db.rollback()
        raise
    finally:
        db.close()


if __name__ == "__main__":
    seed_catalog()
