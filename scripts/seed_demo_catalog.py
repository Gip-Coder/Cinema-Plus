# Screen technology labels that count as "premium_large" / "luxury_recliner"
PREMIUM_LARGE_TYPES = {"IMAX", "IMAX Laser", "4DX", "PXL", "PCX Large Format"}
LUXURY_RECLINER_TYPES = {"Gold Class", "LUXE"}


def _screen(name: str, screen_type: str = "Standard", total_seats: Optional[int] = None) -> Dict:
    if total_seats is not None:
        tier_seats = total_seats
    elif screen_type in PREMIUM_LARGE_TYPES:
        tier_seats = SEAT_TIERS["premium_large"]["total_seats"]
    elif screen_type in LUXURY_RECLINER_TYPES:
        tier_seats = SEAT_TIERS["luxury_recliner"]["total_seats"]
    else:
        tier_seats = SEAT_TIERS["standard"]["total_seats"]
    return {"name": name, "screen_type": screen_type, "total_seats": tier_seats}


