"""Idempotent, additive catalog seeder for a realistic multi-city demo dataset.

This is DELIBERATELY SEPARATE from scripts/seed_db.py (which stays as the
minimal admin-bootstrap + tiny smoke-test dataset it always was). This script
seeds a much larger, real-world catalog: verified Indian cinema venues and a
curated Hollywood/Indian-language movie library, plus the application-
generated operational data (layouts, seats, pricing, shows) needed to make
it actually bookable.

DATA PROVENANCE
----------------
Theatre/movie identity and metadata below were verified via live web
research on 2026-08-29 (see docs/SEEDED_DATA_SOURCES.md for the full
per-entity source list and verification notes). Anything not independently
verifiable was left out rather than invented — see the SOURCES doc for the
explicit list of what was excluded and why.

Everything else generated by this script (seat layouts, seat definitions,
seat pricing, show schedule) is APPLICATION-GENERATED OPERATIONAL DATA
associated with a real venue — it is not, and must not be presented as,
the venue's actual physical seating arrangement.

IDEMPOTENCY
------------
Every insert is gated by a natural-key existence check:
  Movie:   (title, release_date)
  Theatre: (name, city)
  Screen:  (theatre_id, name)
  Show:    (screen_id, movie_id, date, start_time)
Re-running this script only adds what's missing. It never touches Booking
or User records, and never deletes anything except the synthetic
"Grand Plaza Cinema" placeholder — and only after confirming it has no
booking dependencies (see handle_synthetic_placeholder()).

USAGE
------
    python scripts/seed_demo_catalog.py
"""
