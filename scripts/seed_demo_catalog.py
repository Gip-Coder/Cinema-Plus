# ─────────────────────────────────────────────────────────────────────────
def handle_synthetic_placeholder(db: Session) -> None:
    """Safely remove the earlier synthetic 'Grand Plaza Cinema' placeholder
    (fake venue, fake city 'Metropolis, NY') that scripts/seed_db.py used to
    create — but ONLY if nothing depends on it. This never runs raw/destructive
    SQL and never touches Booking/User records; it only ever inspects and,
    if safe, removes rows this same seeding architecture created.
    """
    placeholder = (
        db.query(models.Theatre)
        .filter(models.Theatre.name == "Grand Plaza Cinema", models.Theatre.city == "Metropolis")
        .first()
    )
    if not placeholder:
        return

    screen_ids = [s.id for s in db.query(models.Screen).filter(models.Screen.theatre_id == placeholder.id).all()]
    show_ids = [
        sh.id for sh in db.query(models.Show).filter(models.Show.screen_id.in_(screen_ids)).all()
    ] if screen_ids else []
    dependent_bookings = (
        db.query(models.Booking).filter(models.Booking.show_id.in_(show_ids)).count()
        if show_ids else 0
    )

    if dependent_bookings > 0:
        print(
            f"[SEED WARNING] 'Grand Plaza Cinema' has {dependent_bookings} dependent booking(s) — "
            "NOT deleting. Marking inactive instead so it drops out of customer-facing listings. "
            "Review these bookings manually before any further cleanup."
        )
        placeholder.is_active = False
        db.flush()
        return

    print("[SEED] Removing synthetic 'Grand Plaza Cinema' placeholder (no dependent bookings found)...")
    for screen_id in screen_ids:
        layout_ids = [
            l.id for l in db.query(models.TheatreLayout.id).filter(models.TheatreLayout.screen_id == screen_id).all()
        ]
        if layout_ids:
            db.query(models.SeatDefinition).filter(
                models.SeatDefinition.layout_id.in_(layout_ids)
            ).delete(synchronize_session=False)
            db.query(models.TheatreLayout).filter(
                models.TheatreLayout.id.in_(layout_ids)
            ).delete(synchronize_session=False)
        db.query(models.SeatPricing).filter(models.SeatPricing.screen_id == screen_id).delete(synchronize_session=False)
        db.query(models.Show).filter(models.Show.screen_id == screen_id).delete(synchronize_session=False)
    db.query(models.SeatPricing).filter(
        models.SeatPricing.theatre_id == placeholder.id, models.SeatPricing.screen_id.is_(None)
    ).delete(synchronize_session=False)
    db.query(models.Screen).filter(models.Screen.theatre_id == placeholder.id).delete(synchronize_session=False)
    db.delete(placeholder)
    db.flush()
    print("  ✓ Synthetic placeholder removed.")


