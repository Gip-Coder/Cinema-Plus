def get_or_create_movie(db: Session, spec: Dict) -> models.Movie:
    existing = (
        db.query(models.Movie)
        .filter(models.Movie.title == spec["title"], models.Movie.release_date == spec["release_date"])
        .first()
    )
    if existing:
        return existing

    is_upcoming = spec["release_date"] > date.today()
    movie = models.Movie(
        title=spec["title"], genre=spec["genre"], language=spec["language"],
        format="2D", release_date=spec["release_date"],
        running_days=90, poster_url=None, description=spec["description"],
        duration=spec["duration"], rating=spec["rating"],
        status="Coming Soon" if is_upcoming else "Now Showing",
        is_deleted=False,
    )
    db.add(movie)
    db.flush()
    return movie


def seed_movies(db: Session) -> List[models.Movie]:
    print("Seeding movies...")
    movies = [get_or_create_movie(db, spec) for spec in MOVIES]
    db.commit()
    print(f"  ✓ {len(MOVIES)} movies verified/seeded.")
    return movies


