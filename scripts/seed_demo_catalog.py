def get_or_create_theatre(db: Session, spec: Dict) -> models.Theatre:
    existing = (
        db.query(models.Theatre)
        .filter(models.Theatre.name == spec["name"], models.Theatre.city == spec["city"])
        .first()
    )
    if existing:
        return existing
    theatre = models.Theatre(
        name=spec["name"], city=spec["city"], state=spec["state"],
        timezone=spec["timezone"], address=spec["address"],
        description=spec["description"], is_active=True,
    )
    db.add(theatre)
    db.flush()
    print(f"  ✓ Theatre created: {theatre.name} ({theatre.city})")
    return theatre


def get_or_create_screen(db: Session, theatre: models.Theatre, spec: Dict) -> models.Screen:
    existing = (
        db.query(models.Screen)
        .filter(models.Screen.theatre_id == theatre.id, models.Screen.name == spec["name"])
        .first()
    )
    if existing:
        return existing
    screen = models.Screen(
        theatre_id=theatre.id, name=spec["name"], screen_type=spec["screen_type"],
        total_seats=spec["total_seats"], is_active=True,
    )
    db.add(screen)
    db.flush()
    return screen


def _layout_template_for(screen: models.Screen) -> str:
    if screen.screen_type in PREMIUM_LARGE_TYPES:
        return "IMAX"
    if screen.screen_type in LUXURY_RECLINER_TYPES:
        return "RECLINER"
    return "STANDARD"


def ensure_published_layout(db: Session, screen: models.Screen) -> None:
    """Reuses layout_generator.py + TheatreLayout/SeatDefinition — the same
    architecture as the admin Layout Designer and scripts/seed_db.py.
    Idempotent: no-op if a published layout already exists for this screen.
    """
    existing = (
        db.query(models.TheatreLayout)
        .filter(models.TheatreLayout.screen_id == screen.id, models.TheatreLayout.status == "published")
        .first()
    )
    if existing:
        return

    template = _layout_template_for(screen)
    layout_data = generate_layout(total_seats=screen.total_seats, template=template)

    layout = models.TheatreLayout(
        theatre_id=screen.theatre_id, screen_id=screen.id,
        layout_name="Default Layout", layout_type=template,
        total_seats=layout_data.total_seats, rows=layout_data.rows, cols=layout_data.cols,
        status="published", version=1, is_published=True,
    )
    db.add(layout)
    db.flush()

    for seat in layout_data.seats:
        db.add(models.SeatDefinition(
            layout_id=layout.id, seat_code=seat.seat_code, row_label=seat.row_label,
            seat_number=seat.seat_number, seat_type=seat.seat_type, category=seat.category,
            position_x=seat.position_x, position_y=seat.position_y, is_active=seat.is_active,
        ))
    db.flush()


# City tier -> base price table (application-generated operational pricing,
# not a claim about the venue's real ticket prices). Metro tier-1 cities get
# a modestly higher base than tier-2 cities, which is realistic behavior for
# Indian multiplex pricing without asserting a specific verified figure.
TIER1_CITIES = {"Mumbai", "New Delhi", "Noida", "Bengaluru", "Chennai", "Hyderabad"}
BASE_PRICES = {
    "tier1": {"Normal": 180.0, "Executive": 260.0, "Premium": 360.0},
    "tier2": {"Normal": 150.0, "Executive": 220.0, "Premium": 300.0},
}
PREMIUM_SCREEN_MULTIPLIER = 1.4


def ensure_seat_pricing(db: Session, theatre: models.Theatre, screens: List[models.Screen]) -> None:
    tier = "tier1" if theatre.city in TIER1_CITIES else "tier2"
    base = BASE_PRICES[tier]

    existing_theatre_wide = (
        db.query(models.SeatPricing)
        .filter(models.SeatPricing.theatre_id == theatre.id, models.SeatPricing.screen_id.is_(None))
        .first()
    )
    if not existing_theatre_wide:
        for category, price in base.items():
            db.add(models.SeatPricing(
                theatre_id=theatre.id, screen_id=None, seat_category=category, base_price=price,
            ))
        db.flush()

    for screen in screens:
        if screen.screen_type not in PREMIUM_LARGE_TYPES and screen.screen_type not in LUXURY_RECLINER_TYPES:
            continue
        existing_override = (
            db.query(models.SeatPricing)
            .filter(models.SeatPricing.theatre_id == theatre.id, models.SeatPricing.screen_id == screen.id)
            .first()
        )
        if existing_override:
            continue
        for category, price in base.items():
            db.add(models.SeatPricing(
                theatre_id=theatre.id, screen_id=screen.id, seat_category=category,
                base_price=round(price * PREMIUM_SCREEN_MULTIPLIER, 2),
            ))
    db.flush()


def seed_theatres(db: Session) -> Dict[str, List[models.Screen]]:
    """Returns {theatre_name: [screens]} for use by show generation."""
    print("Seeding theatres, screens, layouts, and pricing...")
    theatre_screens: Dict[str, List[models.Screen]] = {}
    for spec in THEATRES:
        theatre = get_or_create_theatre(db, spec)
        screens = [get_or_create_screen(db, theatre, s) for s in spec["screens"]]
        for screen in screens:
            ensure_published_layout(db, screen)
        ensure_seat_pricing(db, theatre, screens)
        theatre_screens[spec["name"]] = screens
    db.commit()
    print(f"  ✓ {len(THEATRES)} theatres verified/seeded.")
    return theatre_screens


